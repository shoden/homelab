#!/usr/bin/env bash
# C4 architecture diagrams (Structurizr DSL in doc/architecture/workspace.dsl), run in Docker.
#   ./architecture.sh serve     browse and edit the diagrams live at http://localhost:8080
#   ./architecture.sh check     validate the DSL (also run by CI)
#   ./architecture.sh site      build a self-contained interactive site in doc/architecture/site/ (open index.html;
#                               gitignored, works offline from file://)
#   ./architecture.sh export    regenerate doc/architecture/diagrams/ (Mermaid .mmd and SVG) and the Mermaid
#                               blocks in doc/architecture/diagrams.md
# Override with STRUCTURIZR_IMAGE, PLANTUML_IMAGE and PORT.
set -euo pipefail
cd "$(dirname "$0")"

structurizr_image="${STRUCTURIZR_IMAGE:-structurizr/structurizr:2026.10.26}"
plantuml_image="${PLANTUML_IMAGE:-plantuml/plantuml:1.2026.1}"
dir=doc/architecture
# The containers run as the invoking user so generated files are not owned by root. That uid has no passwd
# entry, so Java's home would be "?" (a stray directory): point it at /tmp.
docker_user=(--user "$(id -u):$(id -g)" -e HOME=/tmp -e JAVA_TOOL_OPTIONS=-Duser.home=/tmp)
run=(docker run --rm "${docker_user[@]}" -v "$PWD/$dir":/work -w /work)

# Colima's bind mounts sometimes serve a stale directory right after the previous run deleted files, and the
# export then fails with NoSuchFileException. Retrying after a pause is enough (native Docker and CI never do).
retry() {
	local attempt
	for attempt in 1 2 3 4 5; do
		"$@" && return 0
		[ "$attempt" = 5 ] && break
		echo "failed (attempt $attempt), retrying..." >&2
		sleep 5
	done
	echo "failed 5 times" >&2
	return 1
}

case "${1:-}" in
serve)
	# `local` takes the workspace.dsl in the mounted directory (it has no -workspace option: that was taken as a
	# path and created a "-workspace" directory with a sample workspace). It also writes .structurizr/ and
	# workspace.json there (gitignored).
	exec docker run --rm "${docker_user[@]}" -p "${PORT:-8080}:8080" -v "$PWD/$dir":/usr/local/structurizr \
		"$structurizr_image" local
	;;
check)
	"${run[@]}" "$structurizr_image" validate -workspace workspace.dsl
	;;
export)
	retry "$0" export-once
	;;
site)
	retry "$0" site-once
	echo "Open $dir/site/index.html in a browser"
	;;
site-once)
	mkdir -p "$dir/site"
	find "$dir/site" -type f -delete
	"${run[@]}" "$structurizr_image" export -workspace workspace.dsl -format static -output site
	;;
export-once)
	# The PlantUML sources are a by-product kept next to the output (a separate scratch directory made the
	# export fail at random with NoSuchFileException under Colima) and removed at the end.
	mkdir -p "$dir/diagrams"
	marker="$(mktemp)"
	"${run[@]}" "$structurizr_image" export -workspace workspace.dsl -format mermaid -output diagrams
	"${run[@]}" "$structurizr_image" export -workspace workspace.dsl -format plantuml/structurizr -output diagrams
	"${run[@]}" "$plantuml_image" -tsvg diagrams/*.puml
	find "$dir/diagrams" -name '*.puml' -delete
	# files of views that no longer exist (everything written above is newer than the marker)
	find "$dir/diagrams" -type f ! -newer "$marker" -delete
	rm -f "$marker"
	rm -rf "$dir/?" # PlantUML's font cache, if Java's home was still "?"
	# the per-view Mermaid goes into one markdown page that GitHub renders
	{
		echo "# Architecture diagrams"
		echo
		echo "Generated by \`./architecture.sh export\` from [workspace.dsl](workspace.dsl). Do not edit."
		echo "SVG versions are in [diagrams/](diagrams/)."
		for f in "$dir"/diagrams/*.mmd; do
			name="$(basename "$f" .mmd)"
			echo
			echo "## ${name#structurizr-}"
			echo
			echo '```mermaid'
			cat "$f"
			echo '```'
		done
	} >"$dir/diagrams.md"
	;;
*)
	echo "Usage: $0 serve|check|export|site" >&2
	exit 1
	;;
esac
